/* Draw a map at 1 cell = 1 canvas px; CSS scales it up with image-rendering: pixelated */
function drawMap(canvas, map) {
  const rows = map.length;
  const cols = Math.max(...map.map(r => r.length));
  canvas.width = cols;
  canvas.height = rows;
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, cols, rows);
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < map[y].length; x++) {
      const c = map[y][x];
      if (c >= '0' && c <= '3') {
        ctx.fillStyle = PAL[+c];
        ctx.fillRect(x, y, 1, 1);
      }
    }
  }
  return canvas;
}

function makeIcon(map) {
  return drawMap(document.createElement('canvas'), map);
}
